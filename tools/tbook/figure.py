FIG_DIR = "figures"
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
TEMPLATE = paths.TEMPLATES / "figure" / "figure.py"
NODE_SHOTS = paths.TOOLS / "node" / "fig-shots.mjs"
# The word that may precede the number of a caption that says nothing else: "图 13", "Figure 2.1", "Fig. 3:".
_FIGURE_WORD_RE = re.compile(r"(?:图|圖|figure|fig|abbildung|abb)\.?", re.I)
_STYLE_RE = re.compile(r"<style>.*?</style>\n?", re.S)
_ROOT_RE = re.compile(r"<svg\b[^>]*>")
_PANEL_RE = re.compile(r'<svg class="tr-fig-panel" x="[^"]*" y="(?P<y>[^"]*)" width="(?P<w>[^"]*)" height="(?P<h>[^"]*)" '
                       r'viewBox="(?P<vb>[^"]*)">\n(?P<body>.*?)\n</svg>', re.S)
SCREEN_EXT = ".screen.svg"
PRINT_EXT = ".print.svg"
PDF_BASE_WIDTH = figkit.MAX_WIDTH  # a figure this wide fills the text column of the PDF and EPUB


class FigureError(figkit.FigureError):
    pass


def esc(text: str) -> str:
    return html.escape(str(text), quote=True)


# --------------------------------------------------------------------------- palettes


@functools.lru_cache(maxsize=1)
def tokens() -> dict:
    return json.loads((paths.THEME / "tokens.json").read_text(encoding="utf-8"))


def palette_rules(name: str) -> str:
    """CSS giving every role its colour in palette ``name`` (``screen`` or ``paper``)."""
    pal = tokens()[name]
    return "".join(f".ts-{r}{{stroke:{pal[t]}}}.tf-{r}{{fill:{pal[t]}}}" for r, t in figkit.ROLES.items())


def style_sheet() -> str:
    """The style element of a canonical figure: the paper palette, and the screen palette where
    the viewer prefers a dark scheme (the file opened on its own, or previewed on GitHub)."""
    return (f"<style>{palette_rules('paper')}@media (prefers-color-scheme:dark){{{palette_rules('screen')}}}</style>")


def materialize(svg: str, palette: str, *, ground: bool = False) -> str:
    """``svg`` (canonical) with only ``palette`` in its style sheet, for renderers that take the
    file as it is (Typst, EPUB readers); ``ground`` puts the palette's page colour behind it."""
    back = f'<rect width="100%" height="100%" fill="{tokens()[palette]["void"]}"/>\n' if ground else ""
    out, n = _STYLE_RE.subn(lambda _m: f"<style>{palette_rules(palette)}</style>\n{back}", svg, count=1)
    if not n:
        raise FigureError("not a canonical figure: no style sheet (regenerate it with ./tbook fig build)")
    return out


def mdbook_css() -> str:
    """Rules that give the inlined figures of the HTML edition their colours from the page's
    ``--tr-*`` tokens. Written into ``tr/`` beside the mdBook theme (:mod:`tbook.html`)."""
    rules = "".join(f".tr-fig .ts-{r}{{stroke:var(--tr-{t})}}.tr-fig .tf-{r}{{fill:var(--tr-{t})}}"
                    for r, t in figkit.ROLES.items())
    return "/* generated by tbook.figure.mdbook_css from tbook.figkit.ROLES - do not edit */\n" + rules + "\n"


# --------------------------------------------------------------------------- scripts and outputs


def figures_dir(book) -> Path:
    return book.dir / FIG_DIR


def script_path(book, name: str) -> Path:
    return figures_dir(book) / f"{name}.py"


def out_path(book, name: str, lang: str) -> Path:
    return figures_dir(book) / f"{name}.{lang}.svg"


def slide_copies(book, name: str, lang: str) -> list[Path]:
    """Copies of figure ``name`` that ``book``'s slide decks show: ``slides/<deck>/img/<name>.<lang>.svg``.
    The decks are dark, and an SVG in an ``<img>`` follows the viewer's colour scheme rather than the
    page, so a copy holds the screen palette only (:func:`slide_svg`); ``build`` keeps it current."""
    return sorted((book.dir / "slides").glob(f"*/img/{name}.{lang}.svg"))


def slide_svg(svg: str) -> str:
    """What a slide deck's copy of the canonical figure ``svg`` holds."""
    return materialize(svg, "screen")


def names(book) -> list[str]:
    """The figures of ``book``: its scripts, except helpers (``_common.py``)."""
    d = figures_dir(book)
    if not d.is_dir():
        return []
    return sorted(p.stem for p in d.glob("*.py") if not p.name.startswith("_"))


def _load(book, name: str):
    path = script_path(book, name)
    if not path.is_file():
        raise FigureError(f"no figure script {paths.rel(path)}")
    d = str(figures_dir(book).resolve())
    spec = importlib.util.spec_from_file_location("tbook_figure_script", path)
    mod = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
    before = set(sys.modules)
    bytecode = sys.dont_write_bytecode
    sys.dont_write_bytecode = True  # no __pycache__ in the book
    sys.path.insert(0, d)
    try:
        spec.loader.exec_module(mod)  # type: ignore[union-attr]
    except figkit.FigureError:
        raise
    except Exception as exc:  # noqa: BLE001 - a script error is reported, not raised through the tool
        raise FigureError(f"{paths.rel(path)}: {type(exc).__name__}: {exc}") from exc
    finally:
        sys.path.remove(d)
        sys.dont_write_bytecode = bytecode
        for key in set(sys.modules) - before:  # helpers are re-read per figure and per book
            f = getattr(sys.modules[key], "__file__", None) or ""
            if f.startswith(d):
                del sys.modules[key]
    return mod


def render(book, name: str, lang: str) -> str:
    """The canonical SVG of figure ``name`` in ``lang``, drawn now from its script."""
    mod = _load(book, name)
    where = paths.rel(script_path(book, name))
    size = getattr(mod, "SIZE", None)
    draw = getattr(mod, "draw", None)
    if not (isinstance(size, (tuple, list)) and len(size) == 2) or not callable(draw):
        raise FigureError(f"{where}: a figure script defines SIZE = (width, height) and draw(fig)")
    alt = getattr(mod, "ALT", "")
    if isinstance(alt, dict):
        alt = alt.get(lang) or alt.get("en") or ""
    if not str(alt).strip():
        raise FigureError(f"{where}: ALT has no text for {lang!r} (what a reader who cannot see the figure is told)")
    try:
        fig = figkit.Figure(name, lang, size[0], size[1], alt=str(alt), wrap=bool(getattr(mod, "WRAP", False)),
                            markup=getattr(mod, "MARKUP", 1))
        draw(fig)
        return fig.svg()
    except figkit.FigureError as exc:
        raise FigureError(f"{where} ({lang}): {exc}") from exc
    except Exception as exc:  # noqa: BLE001
        raise FigureError(f"{where} ({lang}): {type(exc).__name__}: {exc}") from exc


def build(book, only: list[str] | None = None, *, check: bool = False) -> tuple[list[Path], list[str]]:
    """Write (or with ``check`` only compare) the outputs of ``book``'s figures and the copies its
    slide decks show (:func:`slide_copies`). Returns the files that changed (would change) and the
    errors of scripts that could not be drawn."""
    changed: list[Path] = []
    errors: list[str] = []
    for name in only if only is not None else names(book):
        for ed in book.editions:
            try:
                svg = render(book, name, ed.lang)
            except figkit.FigureError as exc:
                errors.append(str(exc))
                continue
            wanted = [(out_path(book, name, ed.lang), svg)]
            wanted += [(p, slide_svg(svg)) for p in slide_copies(book, name, ed.lang)]
            for dst, text in wanted:
                if not dst.is_file() or dst.read_text(encoding="utf-8") != text:
                    changed.append(dst)
                    if not check:
                        dst.write_text(text, encoding="utf-8")
    return changed, errors


def natural_size(svg: str) -> tuple[float, float]:
    m = re.search(r'viewBox="0 0 ([0-9.]+) ([0-9.]+)"', svg)
    if not m:
        raise FigureError("not a canonical figure: no viewBox")
    return float(m.group(1)), float(m.group(2))


def inline_html(svg: str) -> str:
    """The canonical figure as HTML for a page that defines the role classes (:func:`mdbook_css`):
    no style sheet of its own, no fixed size, and for a figure of panels one ``<svg>`` per panel."""
    root = _ROOT_RE.match(svg)
    if not root:
        raise FigureError("not a canonical figure")
    w, _h = natural_size(svg)
    body = _STYLE_RE.sub("", svg[root.end():], count=1).strip("\n")
    body = re.sub(r"\n</svg>\s*$", "", body)
    label = re.search(r'aria-label="([^"]*)"', root.group())
    alt = label.group(1) if label else ""
    body = re.sub(r"^<title>.*?</title>\n?", "", body, count=1, flags=re.S)
    family = re.search(r'font-family="[^"]*"', root.group())
    fam = (" " + family.group()) if family else ""
    aria = f' role="img" aria-label="{alt}"' if alt else ' role="img"'
    if 'data-wrap="1"' in root.group():
        panels = list(_PANEL_RE.finditer(body))
        parts = [f'<svg class="tr-fig tr-fig-part" viewBox="{m.group("vb")}" style="flex-basis:{m.group("w")}px"{fam} '
                 f'aria-hidden="true">\n{m.group("body")}\n</svg>' for m in panels]
        # Panels that share a row sit side by side on a wide screen and shrink together; a figure laid out
        # in several rows keeps its rows there, and on a phone every panel stacks in reading order.
        rows: dict[str, list[str]] = {}
        for m, part in zip(panels, parts):
            rows.setdefault(m.group("y"), []).append(part)
        box = f'style="max-width:{figkit.num(w)}px"{aria}'
        if len(rows) > 1:
            inner = "\n".join('<div class="tr-fig-row tr-fig-wrap">\n' + "\n".join(r) + "\n</div>" for r in rows.values())
            return f'<div class="tr-fig-rows" {box}>\n{inner}\n</div>'
        return f'<div class="tr-fig-row tr-fig-wrap" {box}>\n' + "\n".join(parts) + "\n</div>"
    vb = re.search(r'viewBox="[^"]*"', root.group()).group()  # type: ignore[union-attr]
    return (f'<div class="tr-fig-row">\n<svg class="tr-fig" {vb} style="max-width:{figkit.num(w)}px"{fam}{aria}>\n'
            f"{body}\n</svg>\n</div>")


# --------------------------------------------------------------------------- media interface


def check_ref(book, src: str) -> str | None:
    """Why ``::: {.figure src=…}`` cannot be shown, or None."""
    src = (src or "").strip()
    if not NAME_RE.match(src):
        return (f'figure src="{src}" is not a figure name (lower-case letters, digits and hyphens): it names '
                f"books/{book.slug}/{FIG_DIR}/<name>.py")
    if not script_path(book, src).is_file():
        return f"no figure {paths.rel(script_path(book, src))} (./tbook fig new {book.slug} {src})"
    missing = [paths.rel(out_path(book, src, ed.lang)) for ed in book.editions if not out_path(book, src, ed.lang).is_file()]
    if missing:
        return f"figure {src} is not drawn: {', '.join(missing)} missing (./tbook fig build --book {book.slug})"
    return None


def only_a_number(plain: str) -> bool:
    """True when ``plain`` holds a number and nothing to read: digits and punctuation, perhaps after
    the word for a figure (one pass over the text; no pattern that could backtrack)."""
    s = plain.lstrip(string.punctuation + string.whitespace + "（【《「“‘")
    m = _FIGURE_WORD_RE.match(s)
    if m:
        s = s[m.end():]
    return any(ch.isdigit() for ch in s) and not any(ch.isalpha() or ch == "_" for ch in s)


def caption_problem(text: str) -> str | None:
    """Why ``text`` is no caption (empty, or only a number), or None."""
    plain = re.sub(r"\s+", " ", text or "").strip()
    if not re.search(r"\w", plain):
        return "has no caption: say in one sentence what the figure shows"
    if only_a_number(plain):
        return f'has a placeholder caption ("{plain}"): say in one sentence what the figure shows'
    return None


def check(book) -> list[Issue]:
    """Scripts that cannot be drawn or whose committed output is stale (errors); outputs without a
    script (warnings). Figures that no chapter cites are :func:`tbook.check.check_unused_figures`'s."""
    issues: list[Issue] = []
    d = figures_dir(book)
    if not d.is_dir():
        return issues
    known = names(book)
    for name in known:
        if not NAME_RE.match(name):
            issues.append(Issue("error", script_path(book, name), 0,
                                f"figure name {name!r}: use lower-case letters, digits and hyphens"))
    changed, errors = build(book, [n for n in known if NAME_RE.match(n)], check=True)
    for msg in errors:
        issues.append(Issue("error", d, 0, msg))
    for p in changed:
        if p.parent.name == "img" and p.parent.parent.parent.name == "slides":
            what = "is not the screen-palette copy of the figure its script draws now (slide decks are dark)"
        else:
            what = "is stale: its script draws something else" if p.is_file() else "has not been generated"
        issues.append(Issue("error", p, 0, f"{what} (run ./tbook fig build --book {book.slug} and commit the result)"))
    langs = {ed.lang for ed in book.editions}
    for p in sorted(d.glob("*.svg")):
        stem, _, lang = p.name[:-4].rpartition(".")
        if stem not in known or lang not in langs:
            issues.append(Issue("warning", p, 0, "no figure script draws this file (figures are generated: "
                                                 f"{FIG_DIR}/<name>.py → <name>.<lang>.svg); delete it or add its script"))
    issues.extend(phone_issues(book, [n for n in known if NAME_RE.match(n)]))
    return issues


# --------------------------------------------------------------------------- labels on a phone

PHONE_WIDTH = 358  # the text column of a 390 px phone screen (16 px margins): a wider figure is shown this wide
PHONE_MIN_FONT = 10.0  # the smallest label a reader can still read there, in CSS pixels
PHONE_SEVERITIES = ("warning", "error")
_FONT_SIZE_RE = re.compile(r'font-size="([0-9.]+)"')
_PANEL_WIDTH_RE = re.compile(r'<svg class="tr-fig-panel" x="[^"]*" y="[^"]*" width="([0-9.]+)"')


def phone_label(svg: str) -> tuple[float, float, float] | None:
    """(smallest label on a phone, its size at the natural size, the width that is scaled) of the
    canonical figure ``svg``, or None when it has no text. A figure is shown at ``min(1, 358 / width)``
    of its natural size; one made of panels (``WRAP = True``) stacks them on a phone, so its widest
    panel decides. Sub- and superscripts (``font-size="72%"``) follow their label and are not counted."""
    sizes = [float(v) for v in _FONT_SIZE_RE.findall(svg)]
    if not sizes:
        return None
    root = _ROOT_RE.match(svg)
    width = natural_size(svg)[0]
    if root and 'data-wrap="1"' in root.group():
        panels = [float(v) for v in _PANEL_WIDTH_RE.findall(svg)]
        width = max(panels) if panels else width
    smallest = min(sizes)
    return smallest * min(1.0, PHONE_WIDTH / width), smallest, width


def phone_severity() -> str:
    """How ``[figures] phone_labels`` of site.toml reports a label too small on a phone: "warning"
    (default) or "error"."""
    value = config.load_site().raw.get("figures", {}).get("phone_labels", "warning")
    if value not in PHONE_SEVERITIES:
        raise config.ConfigError(f'site.toml: [figures] phone_labels must be "warning" or "error"; got {value!r}')
    return value


def phone_reading(book, name: str) -> tuple[float, str, float, float] | None:
    """(smallest label on a phone, edition, natural size, scaled width) of figure ``name`` over its
    drawn editions (the smallest one), or None when nothing is drawn or it has no text."""
    best = None
    for ed in book.editions:
        p = out_path(book, name, ed.lang)
        if not p.is_file():
            continue
        try:
            got = phone_label(p.read_text(encoding="utf-8"))
        except FigureError:
            continue
        if got and (best is None or got[0] < best[0]):
            best = (got[0], ed.lang, got[1], got[2])
    return best


def phone_problem(book, name: str) -> str | None:
    """Why figure ``name``'s smallest label cannot be read on a phone, with the three ways out; or None."""
    got = phone_reading(book, name)
    if got is None or got[0] >= PHONE_MIN_FONT - 1e-9:
        return None
    value, lang, size, width = got
    narrow = PHONE_WIDTH * size / PHONE_MIN_FONT
    bigger = PHONE_MIN_FONT * width / PHONE_WIDTH
    return (f"figure {name}: its smallest label ({figkit.num(size)} px, {lang}) is {value:.1f} px on a phone, below "
            f"{figkit.num(PHONE_MIN_FONT)} px (a {figkit.num(width)} px wide drawing is shown {PHONE_WIDTH} px wide). "
            f"Make it narrower (width at most {math.floor(narrow)}), split it into panels that stack on a phone "
            f"(WRAP = True, each at most {math.floor(narrow)} wide), or enlarge its labels to at least "
            f"{math.ceil(bigger * 10) / 10:g} px")


def phone_issues(book, only: list[str] | None = None) -> list[Issue]:
    """:func:`phone_problem` of ``book``'s figures, at the severity site.toml asks for (:func:`phone_severity`)."""
    try:
        severity = phone_severity()
    except config.ConfigError as exc:
        return [Issue("error", paths.SITE_TOML, 0, str(exc))]
    issues = []
    for name in only if only is not None else names(book):
        problem = phone_problem(book, name)
        if problem:
            issues.append(Issue(severity, script_path(book, name), 0, problem))
    return issues


def items(book) -> list[dict]:
    return []  # figures belong to their chapters; the landing page does not list them


def cited_gids(book) -> list[tuple[Path, int, str]]:
    return []  # a figure cites no declaration: what it shows is stated by the chapter around it


def _width_percent(svg: str) -> int:
    w, _ = natural_size(svg)
    return max(20, min(100, round(100 * w / PDF_BASE_WIDTH)))


def render_embed(env, ctx, inner: str, doc) -> str:
    """Markup replacing a ``::: {.figure src=…}`` block for ``ctx.target`` ("mdbook" or "pandoc")."""
    src = (env.attrs.get("src") or "").strip()
    lang = ctx.lang
    caption = inner.strip("\n")
    problem = check_ref(ctx.book, src)
    svg = ""
    if not problem:
        svg = out_path(ctx.book, src, lang).read_text(encoding="utf-8")
        try:
            natural_size(svg)
            materialize(svg, "paper")
        except figkit.FigureError as exc:
            problem = f"figure {src}: {exc}"
    if problem:
        ctx.issues.append(f"{doc.path}: {problem}")
    if ctx.target == "mdbook":
        body = inline_html(svg) if not problem else f'<p class="tr-fig-missing">{esc(src)}</p>'
        out = [f'<figure class="tr-media tr-figure" data-figure="{esc(src)}">', body]
        if caption:
            out += ['<figcaption class="tr-media-caption">', "", caption, "", "</figcaption>"]
        out.append("</figure>")
        return "\n".join(out)
    lines = ["::: {.tr-media .tr-figure}"]
    if not problem:
        rel = f"{FIG_DIR}/{src}.{lang}"
        ctx.book_texts[rel + ".svg"] = materialize(svg, "paper", ground=True)  # EPUB
        ctx.book_texts[rel + PRINT_EXT] = materialize(svg, "paper")
        ctx.book_texts[rel + SCREEN_EXT] = materialize(svg, "screen")
        chapter_dir = posixpath.dirname(doc.chapter.path or "") or "."
        img = posixpath.relpath(posixpath.join(ctx.book_prefix, rel + ".svg"), chapter_dir)
        label = re.search(r'aria-label="([^"]*)"', svg)
        alt = html.unescape(label.group(1)) if label else src
        alt = re.sub(r"([\\\[\]*_`$<>])", r"\\\1", alt)
        # the trailing non-breaking space keeps Pandoc from making the image a figure of its own:
        # the caption is the paragraph below, not the alt text
        lines += [f'![{alt}]({img}){{width={_width_percent(svg)}% tr-fig=1}}\\ ', ""]
    else:
        lines += [f"**{src}**", ""]
    if caption:
        lines += [caption, ""]
    lines.append(":::")
    return "\n".join(lines)


# --------------------------------------------------------------------------- scaffold, preview, CLI


def scaffold(book, name: str) -> Path:
    if not NAME_RE.match(name):
        raise FigureError(f"figure name {name!r}: use lower-case letters, digits and hyphens (e.g. ch02-shadow)")
    dst = script_path(book, name)
    if dst.exists():
        raise FigureError(f"{paths.rel(dst)} already exists")
    if not TEMPLATE.is_file():
        raise FigureError(f"starter template {paths.rel(TEMPLATE)} is missing")
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(TEMPLATE.read_text(encoding="utf-8"), encoding="utf-8")
    return dst


SHOT_VIEWS = ("dark", "light", "phone", "print")


def _shot_page(book, name: str, lang: str, view: str) -> str:
    """A page that shows the figure as the edition does: inlined on the page palette for ``dark``,
    ``light`` and ``phone``; the print file on white paper for ``print``."""
    svg = render(book, name, lang)
    tok = (paths.THEME / "generated" / "tokens.css").read_text(encoding="utf-8")
    fig_css = _figure_css()
    cap = esc(f"{name} · {lang} · {view}")
    if view == "print":
        w, _ = natural_size(svg)
        body = (f'<div class="paper"><div class="col" style="width:{PDF_BASE_WIDTH}px">'
                f'<div style="width:{_width_percent(svg)}%;margin:0 auto">{materialize(svg, "paper")}</div></div></div>')
        cls = "tr-paper"
    else:
        body = (f'<main class="col"><figure class="tr-media tr-figure">{inline_html(svg)}'
                f'<figcaption class="tr-media-caption"><p>{cap}</p></figcaption></figure></main>')
        cls = "tr-paper" if view == "light" else ""
    return (f'<!doctype html><html lang="{esc(lang)}" class="{cls}"><head><meta charset="utf-8">'
            f'<meta name="viewport" content="width=device-width, initial-scale=1"><style>{tok}\n{mdbook_css()}\n{fig_css}\n'
            "html,body{margin:0;background:var(--tr-void);color:var(--tr-ink);font-family:var(--tr-font-body)}"
            ".col{max-width:760px;margin:0 auto;padding:16px;box-sizing:border-box}"
            ".paper{background:#fff;padding:16px}.paper svg{display:block;width:100%;height:auto}"
            f"</style></head><body>{body}</body></html>")


def _figure_css() -> str:
    """The figure rules of the mdBook theme (between the ``tr-figure`` markers of tr-book.css)."""
    css = (paths.THEME / "mdbook" / "tr-book.css").read_text(encoding="utf-8")
    m = re.search(r"/\* tr-figure:start \*/(.*?)/\* tr-figure:end \*/", css, re.S)
    return m.group(1) if m else ""


def shots(book, only: list[str] | None = None, *, langs: list[str] | None = None, views: list[str] | None = None,
          sheet: bool = True) -> int:
    """Screenshots of figures as the editions show them, into ``build/fig-shots/<slug>/``."""
    out = paths.BUILD / "fig-shots" / book.slug
    pages = out / "_pages"
    pages.mkdir(parents=True, exist_ok=True)
    jobs = []
    for name in only or names(book):
        for lang in langs or [ed.lang for ed in book.editions]:
            for view in views or SHOT_VIEWS:
                page = pages / f"{name}.{lang}.{view}.html"
                page.write_text(_shot_page(book, name, lang, view), encoding="utf-8")
                jobs.append({"page": str(page), "out": str(out / f"{name}.{lang}.{view}.png"), "name": name,
                             "lang": lang, "view": view, "width": 390 if view == "phone" else 800})
    if not jobs:
        print("fig shots: no figures")
        return 0
    spec = pages / "jobs.json"
    spec.write_text(json.dumps({"jobs": jobs, "sheet": sheet, "out": str(out)}, ensure_ascii=False), encoding="utf-8")
    node = config_node()
    if node is None:
        print("fig shots: Node.js is not installed", file=sys.stderr)
        return 1
    return subprocess.run([node, str(NODE_SHOTS), str(spec)], cwd=paths.ROOT).returncode


def config_node() -> str | None:
    import shutil

    return shutil.which("node")


USAGE = ("./tbook fig new <book> <name> | fig build [--book <slug>] [--check] [<name> …] | fig list [--book <slug>] | "
         "fig shots <book> [<name> …] [--lang zh] [--view dark|light|phone|print] [--no-sheet]")


def cli(args) -> int:
    cmd = args.fig_cmd
    try:
        if cmd == "new":
            book = config.named_book(args.book_slug)
            dst = scaffold(book, args.name)
            print(f"created {paths.rel(dst)}\nedit it, then: ./tbook fig build --book {book.slug} {args.name} && "
                  f"./tbook fig shots {book.slug} {args.name}\ncite it in every edition: ::: {{.figure src=\"{args.name}\"}}")
            return 0
        if cmd == "shots":
            return shots(config.named_book(args.book_slug), args.names or None, langs=args.lang or None,
                         views=args.view or None, sheet=not args.no_sheet)
        books = config.load_books(args.book or None)
        if cmd == "list":
            rows = []
            for book in books:
                for name in names(book):
                    got = phone_reading(book, name)
                    phone = ("not drawn" if not any(out_path(book, name, ed.lang).is_file() for ed in book.editions)
                             else "no labels" if got is None
                             else f"{got[0]:.1f} px" + ("  < " + figkit.num(PHONE_MIN_FONT) if got[0] < PHONE_MIN_FONT - 1e-9 else ""))
                    rows.append((f"{book.slug}/{name}", phone))
            if rows:
                pad = max(len(r[0]) for r in rows)
                print(f"{'figure':<{pad}}  smallest label on a phone")
                for fig_name, phone in rows:
                    print(f"{fig_name:<{pad}}  {phone}")
            return 0
        if cmd == "build":
            rc = 0
            for book in books:
                only = [n for n in (args.names or [])] or None
                if only:
                    unknown = [n for n in only if n not in names(book)]
                    if unknown and len(books) == 1:
                        raise FigureError(f"{book.slug} has no figure {', '.join(unknown)}")
                    only = [n for n in only if n in names(book)]
                changed, errors = build(book, only, check=args.check)
                for msg in errors:
                    print(f"fig: {msg}", file=sys.stderr)
                for p in changed:
                    print(("stale " if args.check else "wrote ") + paths.rel(p))
                small = phone_issues(book, only)
                for issue in small:
                    print(f"fig: {issue.severity}: {issue.message}", file=sys.stderr)
                n = len(only) if only is not None else len(names(book))
                print(f"fig build: {book.slug}: {n} figure(s), {len(changed)} file(s) "
                      + ("stale" if args.check else "written") + f", {len(errors)} error(s)")
                if errors or (args.check and changed) or any(i.severity == "error" for i in small):
                    rc = 1
            return rc
    except (figkit.FigureError, config.ConfigError) as exc:
        print(f"fig: {exc}", file=sys.stderr)
        return 1
    print(USAGE, file=sys.stderr)
    return 2
