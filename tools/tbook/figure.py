"""Static figures: ``books/<slug>/figures/<name>.py`` → ``<name>.<lang>.svg``, cited with
``::: {.figure src="<name>"}``.

A figure is a script that draws on a :class:`tbook.figkit.Figure` (skills/book-figure)::

    SIZE = (560, 300)                                  # natural size in CSS pixels
    ALT = {"zh": "……", "en": "…"}                      # what a reader who cannot see it is told
    MARKUP = 2                                         # optional: marks nest inside sub- and superscripts
    def draw(fig): ...                                 # fig.t("中文", "English") picks the label

``./tbook fig build`` runs every script once per edition and writes the canonical SVG next to it
(committed, so that ``./tbook check`` can tell when a script and its output have drifted apart). The
canonical file paints by role classes (``ts-cyan``, ``tf-ink`` …) and carries both palettes in its
style sheet. The builds never show it as it is:

* HTML (mdBook): the drawing is inlined without its style sheet, so the roles take the page's
  ``--tr-*`` tokens and follow the theme switch and the browser's print palette; a figure made of
  panels (``WRAP = True``) lays them side by side on a wide screen and stacks them on a phone.
* PDF: two files per figure are staged, ``….screen.svg`` and ``….print.svg`` with that palette
  written in; ``theme/typst/book.typ`` picks one by variant (``tr-fig-ext``).
* EPUB: the paper palette on an opaque page-coloured ground (reading systems have their own themes).

Interface shared with the other media modules (:mod:`tbook.viz`): ``check_ref``, ``check``,
``items``, ``cited_gids``, ``render_embed``, ``cli``.
"""

from __future__ import annotations

import functools
import html
import importlib.util
import json
import math
