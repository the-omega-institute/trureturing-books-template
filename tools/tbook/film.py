"""Book-local films, following the trureturing-film scheme.

A film is generated entirely by code: a deterministic 1920×1080 Canvas animation
(``theme/film/engine.js`` + the film's ``scenes.js``), English narration synthesized locally
with Kokoro-82M, a procedural score, and burned-in Chinese + English subtitles. The
repository holds **source only**. The videos are build outputs like the PDFs: each film is a build unit
(:mod:`tbook.buildcache`, target ``films``, unit ``<slug>/<film id>``) that :func:`build_videos` renders
into ``build/films/<slug>/<film id>/``, and the site hosts them at ``_site/<slug>/films/<film id>/<file>``
(same origin: the right Content-Type and byte ranges, which iOS Safari needs). A film whose inputs did not
change is restored from the cache instead of rendered again (:func:`video_unit` lists the inputs).

Rendering follows ``TBOOK_FILMS``: ``auto`` (default) renders a film whose cache misses when the film
toolchain is present (:func:`toolchain_missing`) and otherwise builds the site without that video, with a
warning; ``require`` fails instead; ``skip`` never renders (a cached film is still restored).

Source layout (``books/<slug>/films/``)::

    <NNN>-<name>/film.json     metadata (schema below)
    <NNN>-<name>/script.json   narration + subtitles, the single source of timing
    <NNN>-<name>/scenes.js     SCENES.<scene id> = S => { … } drawn with the shared engine
    <NNN>-<name>/data/*.json   optional data, inlined as DATA.data.<file stem>
    <NNN>-<name>/poster.jpg    small committed poster (≤ 300 KB), regenerated by hand with `film.sh <dir> poster`;
                               the site and the PDF/EPUB show it (the build never writes it)
    <NNN>-<name>/README.md     optional notes (scenes, sources of every claim)
    <NNN>-<name>/out/          the pipeline's working files (git-ignored): index.html, fonts/, tts/, *.wav, *.mp4

``film.json``::

    {
      "id": "001-golden-deficit",                 = directory name
      "title": "…", "title_zh": "…",              English and Chinese titles
      "summary": "…", "summary_zh": "…",          optional one-paragraph blurbs (landing page, films page)
      "subject": "https://github.com/the-omega-institute/trureturing",
      "subject_commit": "<sha>",                  trureturing commit the film was made against (= the lock commit)
      "released": "YYYY-MM-DD",
      "duration": "m:ss",                         the narrated cut (the build warns when the render differs)
      "resolution": "1280x720@30",                the published video: 1280x720, or 1920x1080 when outputs
                                                  lists a 1080p video; the engine always draws 1920x1080 frames
      "style": "…",
      "narration": {"language": "en", "engine": "Kokoro-82M v1.0 (onnx)", "voice": "af_heart"},
      "subtitles": ["zh", "en"],
      "lean": ["D5/S1/Deficit/DeficitThreeValued.deficit_three_valued", …],   theorems cited (LEAN ✓): GIDs of
                                                  trureturing.lock.json with kind "theorem"
      "outputs": {"narrated_720p": "<file>.mp4", "cover": "<file>.jpg"}   what the build makes, by file name:
                                                  the 720p narrated video the players play and the cover
                                                  (required); "narrated" (1080p), "music_only" (1080p) and
                                                  "music_only_720p" only when listed
    }

``release_tag`` and ``published_tag`` (per-film releases) are no longer used; ``./tbook check`` warns.

``script.json``::

    {"voice": "af_heart", "speed": 0.94, "say": {"word": "pronunciation"}?, "music": {"bpm": 80,
     "progression": "a-minor"}?, "scenes": [{"id": "zeck", "name": "ZECKENDORF"?, "lead": 1.5, "tail": 0.6,
     "lines": [["English narration", "中文字幕"], …], "music": [pad, bass, arp, kick, hat]?,
     "cues": [{"line": 0, "at": 2.5, "kind": "stamp" | "chime"}]?}]}

Embedding in a chapter: ``::: {.film src="001-golden-deficit"}`` (a film of this book) or
``src="trureturing-film:film-<NNN>-v<k>"`` (a release of the-omega-institute/trureturing-film).
HTML gets a ``<video>`` playing ``films/<id>/<outputs.narrated_720p>`` of the site with the committed poster
and download links of the videos film.json lists; the site marks the figure of a film it did not build
(:func:`tbook.site.mark_films`), which then shows the poster and a note instead. PDF/EPUB get the poster, the
caption and the address of the films page when the site has one (:func:`render_embed`). :func:`build`
publishes ``_site/<slug>/films/``.

The render pipeline lives in ``theme/film/`` (``film.sh <film-dir> <step>``); it imports this
module for the provisional timeline, the engine data and what to encode for the outputs (:func:`render_plan`).
"""

