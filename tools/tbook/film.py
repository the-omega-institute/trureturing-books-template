def _caption_title(film: Film | None, lang: str, src: str) -> str:
    if film is None:
        return f"{t(lang, 'external')} · {src[len(EXTERNAL_PREFIX):]}"
    head = t(lang, "film_n", num=film.number) + " · " + film.title(lang)
    duration = (film.meta or {}).get("duration")
    return head + (f" · {duration}" if duration else "")


def render_embed(env, ctx, inner: str, doc) -> str:
    """Markup replacing a ``::: {.film src=…}`` block for ``ctx.target`` ("mdbook" or "pandoc")."""
    src = (env.attrs.get("src") or "").strip()
    lang = ctx.lang
    inner = inner.strip("\n")
    problem = check_ref(ctx.book, src)
    if problem:
        ctx.issues.append(f"{doc.path}: {problem}")
    ext = external_ref(src)
    film = None if ext or problem else get(ctx.book, src)
    head = _caption_title(film, lang, src)
    if film is not None and not film.poster.is_file():
        ctx.issues.append(f"{doc.path}: film {film.id}: no {POSTER}; the player has no poster")

    if ctx.target == "mdbook":
        depth = (doc.chapter.path or "").count("/")
        up = "../" * (depth + 1)  # from <slug>/<lang>/<chapter>.html to <slug>/
        figure_attrs = f' data-film="{esc(src)}"'
        links: list[str] = []
        if ext:
            player = (f'<video class="tr-film-player" controls preload="none" playsinline poster="{esc(ext["cover"])}" '
                      f'title="{esc(head)}">\n<source src="{esc(ext["narrated"])}" type="video/mp4">\n</video>')
            links += [f'<a href="{esc(ext["narrated"])}" target="_blank" rel="noopener">▶ {esc(config.s(lang, "ui.watch"))}</a>',
                      f'<a href="{esc(ext["page"])}" target="_blank" rel="noopener">⬇ {esc(config.s(lang, "ui.download"))}</a>']
        elif film is not None:
            player, files, fallback = _local_player(film, lang, head, up)
            # the site adds tr-film-unbuilt to figures whose data-tr-video it does not host (tbook.site.mark_films);
            # CSS then shows the fallback (poster, note) instead of the player and the download links
            figure_attrs += f' data-tr-video="{esc(film.site_path(PLAYER_OUTPUT))}"'
            player += "\n" + fallback
            links += [f'<span class="tr-film-files">{files}</span>',
                      f'<span class="tr-film-note tr-film-fallback">{esc(t(lang, "unbuilt"))}</span>',
                      f'<a href="{esc(up)}films/index.html?lang={esc(lang)}#{esc(film.id)}">{esc(t(lang, "page"))}</a>']
        else:
            player = f'<div class="tr-film-missing">{esc(config.s(lang, "ui.poster_unavailable"))}</div>'
        return "\n".join([
            f'<figure class="tr-media tr-film"{figure_attrs}>',
            player,
            '<figcaption class="tr-media-caption">',
            "",
            inner or esc(head),
            "",
            f'<div class="tr-media-links">{"".join(links)}</div>' if links else "",
            "</figcaption>",
            "</figure>",
        ])

    # pandoc (PDF / EPUB): a static card. This output does not pass through render's link rewriting, so the
    # poster is registered in ctx.book_files and addressed under ctx.book_prefix (_book/…) like ../assets links.
    # It links the film on the published site (site.base_url); without one the poster stands alone.
    note = config.s(lang, "ui.film_static_note")
    url = ext["page"] if ext else page_url(ctx.site, film) if film is not None else ""
    lines = ["::: {.tr-media .tr-film}"]
    if film is not None and film.poster.is_file():
        ctx.book_files.add(film.poster.resolve())
        chapter_dir = posixpath.dirname(doc.chapter.path or "") or "."
        img = posixpath.relpath(posixpath.join(ctx.book_prefix, "films", film.id, POSTER), chapter_dir)
        alt = head.replace("[", "\\[").replace("]", "\\]")
        lines += [f"![{alt}]({img}){{width=100%}}", ""]
        if not inner:
            lines += [f"**{head}**", ""]
    else:
        lines += [f"**{head}**", ""]
    if inner:
        lines += [inner, ""]
    if url:
        # a hard line break keeps the long address from stretching the justified note line
        lines += [f"{note}\\", f"<{url}>"]
    while lines[-1] == "":
        lines.pop()
    lines.append(":::")
    return "\n".join(lines)


def _local_player(film: Film, lang: str, title: str, up: str) -> tuple[str, str, str]:
    """(player, download links, fallback) of a local film for a page at ``up`` below the book (``<slug>/``).

    The player plays the 720p narrated video with the committed poster; the download links are the videos
    film.json lists (:data:`DOWNLOADS`), so none names a file the build does not make. ``data-tr-poster`` /
    ``data-tr-src`` carry the targets relative to the book: mdBook's print.html copies chapters of every depth to
    ``<lang>/`` without rewriting video posters and sources, and :func:`tbook.site.fix_print_media` repairs them
    from these.
    The fallback (the poster, or a placeholder without one) shows when the site did not build the video.
    """
    poster = f"films/{film.id}/{POSTER}" if film.poster.is_file() else ""
    video = film.site_path(PLAYER_OUTPUT)
    poster_attr = f' poster="{esc(up + poster)}" data-tr-poster="{esc(poster)}"' if poster else ""
    player = (f'<video class="tr-film-player" controls preload="metadata" playsinline{poster_attr} title="{esc(title)}">\n'
              f'<source src="{esc(up + video)}" data-tr-src="{esc(video)}" type="video/mp4">\n</video>')
    files = "".join(f'<a href="{esc(up + film.site_path(key))}" download>⬇ {esc(t(lang, label))}</a>'
                    for key, label in DOWNLOADS if film.listed(key))
    if poster:
        fallback = f'<img class="tr-film-poster tr-film-fallback" src="{esc(up + poster)}" alt="{esc(title)}" loading="lazy">'
    else:
        fallback = f'<div class="tr-film-missing tr-film-fallback">{esc(t(lang, "unbuilt"))}</div>'
    return player, files, fallback


