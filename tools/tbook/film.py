def model_dir() -> Path:
    """``$KOKORO_MODEL_DIR``, default ``<film cache>/models``."""
    return Path(os.environ.get("KOKORO_MODEL_DIR") or film_cache() / "models")


def film_python() -> str:
    """The Python that runs the pipeline: ``$PYTHON``, else the venv theme/film/setup.sh creates
    (``<film cache>/venv``), else ``python3`` on PATH. theme/film/film.sh picks the same one."""
    if os.environ.get("PYTHON"):
        return os.environ["PYTHON"]
    venv = film_cache() / "venv" / "bin" / "python"
    if venv.is_file() and os.access(venv, os.X_OK):
        return str(venv)
    return shutil.which("python3") or sys.executable


def ffmpeg_path() -> str:
    """``$FFMPEG``, else ``ffmpeg`` on PATH ('' when neither)."""
    return os.environ.get("FFMPEG") or shutil.which("ffmpeg") or ""


def font_package(pkg: str) -> Path | None:
    """The @fontsource package directory of ``pkg`` (``$FILM_FONTS_DIR``, node_modules, or the copy
    setup.sh fetches into ``<film cache>/fonts``)."""
    candidates = []
    if os.environ.get("FILM_FONTS_DIR"):
        base = Path(os.environ["FILM_FONTS_DIR"])
        candidates += [base / "@fontsource" / pkg, base / pkg]
    candidates += [paths.ROOT / "node_modules" / "@fontsource" / pkg, film_cache() / "fonts" / pkg]
    for c in candidates:
        if (c / "files").is_dir():
            return c
    return None


def _npm_packages() -> dict[str, list[str]]:
    """Versions and integrity hashes, from package-lock.json, of the npm packages a render uses: the
    @fontsource fonts the page inlines and Playwright (whose Chromium renders without PW_CHROMIUM_PATH)."""
    try:
        lock = json.loads((paths.ROOT / "package-lock.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    wanted = {f"node_modules/@fontsource/{pkg}" for pkg, _, _ in FONT_PLAN}
    wanted |= {"node_modules/playwright-chromium", "node_modules/playwright-core"}
    pkgs = lock.get("packages") or {}
    return {name: [str(pkgs[name].get("version", "")), str(pkgs[name].get("integrity", ""))]
            for name in sorted(wanted) if isinstance(pkgs.get(name), dict)}


def video_unit(site: config.Site, film: Film) -> buildcache.Unit:
    """The build unit of a film's videos (target ``films``, outputs ``build/films/<slug>/<id>/``).

    Its key covers what the videos depend on: the film's files (not ``out/``, the committed poster or its
    README; film.json is one, so listing another output renders again), ``theme/film/`` (not the films page
    assets in ``site/``), ``theme/generated/tokens.mjs``, ``tools/tbook/film.py``, the data the engine draws
    (:func:`engine_data`: the book's code, version and titles, the cited Lean declarations and the pinned
    commit, the in-frame strings), the npm packages of the fonts and of Playwright (which fixes its
    Chromium), the Kokoro model release and Node's major version. ``theme/film/requirements.txt`` pins the Python packages. Not the site's address: the videos
    are the same wherever the site is served. Not the probed ffmpeg, Chromium or film Python either
    (:func:`tbook.buildcache.series`): a build without the film toolchain (``TBOOK_FILMS=auto|skip``) must
    find the same key to restore the videos, and a new ffmpeg package revision on the runner does not
    change what a film shows.
    """
    where = paths.rel(film.dir)
    inputs = (buildcache.Inputs()
              .files(film.dir, exclude=(f"/{where}/{POSTER}", f"/{where}/README.md", f"/{where}/out/"))
              .files(THEME_FILM, exclude=("/theme/film/site/",))
              .files(paths.GENERATED / "tokens.mjs", paths.TOOLS / "tbook" / "film.py")
              .text("engine", engine_data(film))
              .text("npm", _npm_packages())
              .text("kokoro", KOKORO_RELEASE)
              .text("node", buildcache.node_version()))
    return buildcache.Unit("films", f"{film.book.slug}/{film.id}", inputs, [film.build_dir])


def units(site: config.Site, book: config.Book) -> list[buildcache.Unit]:
    """One build unit per film of ``book`` (:func:`video_unit`), for :func:`tbook.buildcache.units`."""
    return [video_unit(site, f) for f in films(book) if f.meta is not None]


def toolchain_missing() -> list[str]:
    """What a render needs and this machine lacks (empty when the film toolchain is complete): ffmpeg,
    Node with Playwright and a Chromium, the film Python packages, the Kokoro model and the fonts."""
    from . import doctor

    missing = []
    if not ffmpeg_path():
        missing.append("ffmpeg (install it, e.g. apt-get install ffmpeg, or set FFMPEG)")
    if not node_executable():
        missing.append("node")
    if not any((paths.ROOT / "node_modules" / p).is_dir() for p in ("playwright-chromium", "playwright")):
        missing.append("Playwright (npm ci)")
    if not doctor.chromium_path():
        missing.append("Chromium (set PW_CHROMIUM_PATH or run npx playwright install chromium)")
    python = film_python()
    try:
        r = subprocess.run([python, "-c", "import numpy, scipy.signal, soundfile, kokoro_onnx"],
                           capture_output=True, timeout=120)
        ok = r.returncode == 0
    except (OSError, subprocess.SubprocessError):
        ok = False
    if not ok:
        missing.append(f"the film Python packages for {python} (theme/film/setup.sh)")
    absent = [f for f in KOKORO_FILES if not (model_dir() / f).is_file()]
    if absent:
        missing.append(f"the Kokoro model ({', '.join(absent)} in {model_dir()}; theme/film/setup.sh)")
    fonts = [pkg for pkg, _, _ in FONT_PLAN if font_package(pkg) is None]
    if fonts:
        missing.append(f"the fonts @fontsource/{{{','.join(fonts)}}} (npm ci, or theme/film/setup.sh)")
    return missing


def render_videos(film: Film, dest: Path) -> None:
    """Render the film with ``theme/film/film.sh <dir> all <output key>…`` (``FILM_STRICT=1``: narrated timing
    only) in its ``out/`` and copy the videos into ``dest``. The keys are the outputs film.json lists
    (:meth:`Film.videos`), passed explicitly; the pipeline encodes only what they need (:func:`render_plan`:
    no 1080p master without a 1080p video, no music-only mix without a music-only video). Writes no
    committed file: the cover goes to ``out/``, the committed ``poster.jpg`` is only written by the
    ``poster`` step, by hand."""
    env = dict(os.environ, FILM_STRICT="1", PYTHON=film_python())
    env.pop("FILM_OUTPUTS", None)
    if ffmpeg_path():
        env["FFMPEG"] = ffmpeg_path()
    keys = list(film.videos())
    r = subprocess.run([str(THEME_FILM / "film.sh"), str(film.dir), "all", *keys], cwd=paths.ROOT, env=env)
    if r.returncode != 0:
        raise FilmError(f"{film.book.slug}/{film.id}: theme/film/film.sh all exited with {r.returncode} (see above)")
    names = list(film.videos().values())
    missing = [n for n in names if not (film.out / n).is_file()]
    if missing:
        raise FilmError(f"{film.book.slug}/{film.id}: the render did not write out/{', out/'.join(missing)}")
    dest = Path(dest)
    tmp = dest.with_name(f".{dest.name}.tmp")
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    for n in names:
        shutil.copy2(film.out / n, tmp / n)
    shutil.rmtree(dest, ignore_errors=True)
    tmp.rename(dest)
    try:
        measured = json.loads((film.out / "timeline.json").read_text(encoding="utf-8"))["duration"]
    except (OSError, ValueError, KeyError):
        return
    declared = str((film.meta or {}).get("duration", ""))
    if declared != format_duration(float(measured)):
        _warn(f"{paths.rel(film.dir)}/film.json: duration is {declared!r}, the rendered cut is "
              f"{format_duration(float(measured))} ({float(measured):.2f} s); update film.json")


def build_videos(site: config.Site, book: config.Book, *, mode: str | None = None) -> dict[str, str]:
    """Render or restore the videos of every film of ``book`` into ``build/films/<slug>/<id>/``.

    Each film is a build unit (:func:`video_unit`) run through :func:`tbook.buildcache.run`: restored from the
    local store or (``TBOOK_CACHE_REMOTE=1``) a release when its key is cached, else rendered
    (:func:`render_videos`) according to ``mode`` (default ``$TBOOK_FILMS``): ``auto`` renders when the
    toolchain is complete (:func:`toolchain_missing`) and otherwise leaves the film out with a warning,
    ``require`` raises :class:`FilmError` instead, ``skip`` never renders. A film left out has no build
    directory, so no video of older inputs is published. Returns {film id: "cached" | "release" | "built" |
    "skipped"}.
    """
    mode = mode or films_mode()
    if mode not in FILMS_MODES:
        raise FilmError(f"films mode {mode!r}: expected one of {', '.join(FILMS_MODES)}")
    _raise_errors(book)
    status: dict[str, str] = {}
    for film in films(book):
        if film.meta is None:
            continue
        unit = video_unit(site, film)
        label = f"{book.slug}/{film.id}"

        def render(film: Film = film, unit: buildcache.Unit = unit, label: str = label) -> None:
            if mode == "skip":
                raise _NotRendered("TBOOK_FILMS=skip")
            missing = toolchain_missing()
            if missing:
                why = "the film toolchain is incomplete: " + "; ".join(missing)
                if mode == "require":
                    raise FilmError(f"film {label}: {why}")
                raise _NotRendered(why)
            print(f"  film {label}: rendering (key {unit.key[:12]})", flush=True)
            render_videos(film, unit.outputs[0])
            # the cache stores the directory: refuse it unless it holds every output film.json lists
            absent = [n for n in film.videos().values() if not (unit.outputs[0] / n).is_file()]
            if absent:
                raise buildcache.MissingOutput(f"{unit.label}: the render did not write {', '.join(absent)}")

        try:
            status[film.id] = buildcache.run(unit, render, repo=site.repo or None)
        except _NotRendered as exc:
            shutil.rmtree(unit.outputs[0], ignore_errors=True)
            _warn(f"film {label} was not built ({exc}); the site shows its poster and \"video not built\"")
            status[film.id] = "skipped"
    return status


