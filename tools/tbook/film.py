    mode = (os.environ.get("TBOOK_FILMS") or "auto").strip().lower()
    if mode not in FILMS_MODES:
        raise FilmError(f"TBOOK_FILMS={mode!r}: expected one of {', '.join(FILMS_MODES)}")
