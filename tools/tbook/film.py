    num, tag = m.group("num"), f"film-{m.group('num')}-v{m.group('ver')}"
    assets = f"https://github.com/{EXTERNAL_REPO}/releases/download/{tag}/"
    return {
        "num": num,
        "tag": tag,
        "narrated": f"{assets}TRURETURING_{num}_narrated_EN_subs_ZH-EN.mp4",
        "cover": f"{assets}TRURETURING_{num}_cover.jpg",
        "page": f"https://github.com/{EXTERNAL_REPO}/releases/tag/{tag}",
        "repo": f"https://github.com/{EXTERNAL_REPO}",
    }


