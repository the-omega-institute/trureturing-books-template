def published_registry(site: config.Site, book: config.Book, lock: lean.Lock | None,
                       built: set[str] | frozenset[str] = frozenset()) -> dict:
    """``films.json`` next to the films page; ``videos`` ({output key: path relative to the page}) only for
    the films in ``built``."""
    data: dict[str, Any] = {"version": 2, "book": book.slug}
    if lock:
        data["trureturing"] = {"repo": lock.repo, "commit": lock.commit}
    data["films"] = []
    for film in films(book):
        if film.meta is None:
            continue
        data["films"].append({
            "id": film.id, "number": film.number, "title": film.title("en"), "title_zh": film.title("zh"),
            "summary": film.summary("en"), "summary_zh": film.summary("zh"),
            "duration": film.meta.get("duration", ""), "released": film.meta.get("released", ""),
            "subject_commit": film.meta.get("subject_commit", ""),
            "poster": f"{film.id}/{POSTER}" if film.poster.is_file() else "",
            "built": film.id in built,
            "videos": {k: f"{film.id}/{v}" for k, v in film.videos().items()} if film.id in built else {},
            "page": page_url(site, film) or None,
            "lean": [{"gid": r["gid"], "name": r["name"], "href": r["url"], "kind": r["kind"]}
                     for r in lean_refs(film.lean, lock)],
        })
    return data


def _raise_errors(book: config.Book) -> None:
    """:class:`FilmError` listing the book's film errors (the same as ``./tbook check`` reports), if any."""
    problems = [i for i in check(book) if i.severity == "error"]
    if problems:
        shown = "\n  ".join(i.format() for i in problems[:12])
        more = f"\n  … and {len(problems) - 12} more" if len(problems) > 12 else ""
        raise FilmError(f"{book.slug}: {len(problems)} film error(s):\n  {shown}{more}")


def _place(src: Path, dst: Path) -> None:
    """``dst`` with the content of ``src``: a hard link where the file system allows it (videos are large),
    else a copy. Nothing writes build files in place (the cache replaces them), so the link stays valid."""
    dst.unlink(missing_ok=True)
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def host_videos(film: Film, dest: Path) -> bool:
    """Put the film's videos (``build/films/<slug>/<id>/``) into ``dest`` (``_site/<slug>/films/<id>/``).
    False, and nothing copied, when the build has not written all of them."""
    names = list(film.videos().values())
    if not all((film.build_dir / n).is_file() for n in names):
        return False
    dest.mkdir(parents=True, exist_ok=True)
    for n in names:
        _place(film.build_dir / n, dest / n)
    return True


def build(site, book, out_dir: Path, *, videos: bool = True) -> dict[str, str]:
    """Publish the book's films page, posters and videos into ``out_dir`` (``_site/<slug>/films/``).

    First renders or restores the videos (:func:`build_videos`, unless ``videos`` is False), then hosts the
    videos of every film the build has at ``<id>/<file>``; the others get their poster and "video not
    built". Raises :class:`FilmError` when a film has errors (the same as ``./tbook check`` reports) or a
    render fails. A book without ``films/`` publishes nothing. Returns :func:`build_videos`'s statuses.
    """
    out_dir = Path(out_dir)
    if not film_dirs(book):
        return {}
    _raise_errors(book)
    status = build_videos(site, book) if videos else {}
    lock = _lock()
    if out_dir.exists():
        shutil.rmtree(out_dir)
    assets = out_dir / "assets"
    assets.mkdir(parents=True)
    tokens_css = paths.GENERATED / "tokens.css"
    if not tokens_css.exists():
        raise FilmError(f"{paths.rel(tokens_css)} is missing; run ./tbook theme")
    shutil.copyfile(tokens_css, assets / "tokens.css")
    for name in ("films.css", "films.js"):
        src = THEME_FILM / "site" / name
        if not src.exists():
            raise FilmError(f"films page asset missing: {paths.rel(src)}")
        shutil.copyfile(src, assets / name)
    built: set[str] = set()
    for film in films(book):
        if film.poster.is_file():
            (out_dir / film.id).mkdir(parents=True, exist_ok=True)
            shutil.copyfile(film.poster, out_dir / film.id / POSTER)
        if film.meta is not None and host_videos(film, out_dir / film.id):
            built.add(film.id)
    (out_dir / "index.html").write_text(hub_html(site, book, lock, built), encoding="utf-8")
    (out_dir / "films.json").write_text(json.dumps(published_registry(site, book, lock, built), ensure_ascii=False,
                                                   indent=2) + "\n", encoding="utf-8")
    return status


